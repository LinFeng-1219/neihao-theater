def emit_plot(plot):
    parts = []
    for key in ['start', 'ma', 'mb', 'p1', 'p2', 'e1', 'e2', 'e3', 'e4']:
        if key not in plot:
            continue
        n = plot[key]
        fields = []
        if 'at' in n:
            fields.append('at:' + str(n['at']))
        for f in ['title', 'body']:
            if f in n:
                fields.append(f + ':' + jstr(n[f]))
        if 'opts' in n:
            oj = ','.join(
                '{t:' + jstr(o['t']) + ',fx:' + str(o['fx']) +
                (',thought:' + jstr(o['thought']) if o.get('thought') else '') +
                (',d:' + str(o['d']) if o.get('d') else '') +
                (',next:' + jstr(o['next']) if o.get('next') else '') +
                (',end:' + jstr(o['end']) if o.get('end') else '') + '}'
                for o in n['opts'])
            fields.append('opts:[' + oj + ']')
        for f in ['truth', 'reply', 'care', 'careV', 'nx']:
            if f in n:
                fields.append(f + ':' + jstr(n[f]))
        parts.append(key + ':{' + ','.join(fields) + '}')
    return 'plot:{' + ','.join(parts) + '}'

