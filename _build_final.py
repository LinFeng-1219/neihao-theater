def gen(spec):
    js = '['
    stack = []
    need_comma = False
    for raw in spec.strip('\n').split('\n'):
        if not raw.strip():
            continue
        d = (len(raw) - len(raw.lstrip())) // 2
        t = raw.strip()
        while stack and stack[-1] >= d:
            js += ']}'
            stack.pop()
            need_comma = True
        if need_comma:
            js += ','
        need_comma = False
        js += "{t:" + json.dumps(t, ensure_ascii=False) + ",k:["
        stack.append(d)
    while stack:
        js += ']}'
        stack.pop()
    js += ']'
    return js

